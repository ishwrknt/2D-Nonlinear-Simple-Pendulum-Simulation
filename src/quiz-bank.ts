// Correct answer is first here; attempt construction shuffles choices and remaps the key.
function q(
  id: string,
  topic: string,
  prompt: string,
  answer: string,
  wrong: string[],
  explanation: string,
  cases: Question["cases"],
  watch: string,
): Question {
  return {
    id,
    topic,
    prompt,
    options: [answer, ...wrong],
    correct: 0,
    explanation,
    cases,
    watch,
  };
}
